def main(show_plot: bool = True, compact: bool = False) -> None:
    """Main function to run complete wavelength sensitivity analysis.
    
    Args:
        show_plot: If True, display the plot interactively (default: True)
        compact: If True, use compact 36×30 mm size. If False, use normal 6×5 inch size (default: False)
    """
    print("=" * 70)
    print("🎨 Complete Sensitivity Analysis")
    print("=" * 70)
    print("This script combines:")
    print("  1. Parameter sensitivity analysis from HDF5 files")
    print("  2. Wavelength sensitivity plotting")
    print("  3. Q-factor sensitivity plotting")
    print("=" * 70)
    
    # Set up paths
    results_dir = REPO_ROOT / "data" / "results" / "sensitivity"
    figures_dir = REPO_ROOT / "figures"
    figures_dir.mkdir(parents=True, exist_ok=True)
    
    csv_path = results_dir / "summary_all_modes.csv"
    
    # Step 1: Load and analyze HDF5 files
    print(f"\n📊 Step 1: Analyzing simulation results from {results_dir}")
    print(f"Q-factor threshold: {q_threshold}")
    
    if not results_dir.exists():
        print(f"❌ Results directory not found: {results_dir}")
        return
    
    data = load_all_modes_data(results_dir)
    
    # Step 2: Save CSV summary
    print(f"\n💾 Step 2: Saving mode summary to CSV...")
    save_mode_summary_csv(data, csv_path)

    # Step 3: Load CSV data for plotting
    print(f"\n📁 Step 3: Loading data from CSV for plotting...")
    try:
        plot_data = load_saved_mode_data(csv_path)
        print("✅ Data loaded successfully")
    except Exception as e:
        print(f"❌ Error loading data: {e}")
        return
    
    # Step 4: Create wavelength plot
    size_label = "compact" if compact else "normal"
    print(f"\n🎨 Step 4: Creating {size_label} wavelength plot...")
    wavelength_path = figures_dir / "wavelength_sensitivity_compact"
    fig_wl, ax_wl = create_wavelength_plot(plot_data, wavelength_path, compact=compact)
    
    # Step 5: Create Q-factor plot
    print(f"\n🎨 Step 5: Creating {size_label} Q-factor plot...")
    qfactor_path = figures_dir / "q_factor_sensitivity_compact"
    fig_q, ax_q = create_q_factor_plot(plot_data, qfactor_path, compact=compact)
    
    # Show plots if requested
    if show_plot:
        print("\n📊 Displaying plots...")
        plt.show()
    else:
        plt.close(fig_wl)
        plt.close(fig_q)
    
    print("\n" + "=" * 70)
    print("✅ COMPLETE!")
    print("=" * 70)
    print(f"📁 Generated files:")
    print(f"  - CSV summary: {csv_path}")
    if compact:
        print(f"  - Wavelength PNG: {wavelength_path.with_suffix('.png')}")
        print(f"  - Wavelength SVG: {wavelength_path.with_suffix('.svg')}")
        print(f"  - Q-factor PNG: {qfactor_path.with_suffix('.png')}")
        print(f"  - Q-factor SVG: {qfactor_path.with_suffix('.svg')}")
    else:
        print(f"  - Wavelength PNG: {wavelength_path.parent / f'{wavelength_path.name}_normal.png'}")
        print(f"  - Wavelength SVG: {wavelength_path.parent / f'{wavelength_path.name}_normal.svg'}")
        print(f"  - Q-factor PNG: {qfactor_path.parent / f'{qfactor_path.name}_normal.png'}")
        print(f"  - Q-factor SVG: {qfactor_path.parent / f'{qfactor_path.name}_normal.svg'}")


