# Define colors at the beginning
COLORS = {
    'width': '#4a2c5a',      # Dark purple
    'radius': '#b84d8f',     # Pink
    'thickness': '#f4c26f'   # Light orange
}

MARKERS = {
    'width': 'o',
    'radius': 's', 
    'thickness': '^'
}

q_threshold = 100


def load_all_modes_data(results_dir: Path) -> dict[str, list[tuple[int, float, float, str]]]:
    """Load Q-factor and wavelength data for ALL modes in parameter variations."""
    # Include variations: m30, m20, m15, m10, p10, p15, p20, p30
    pat = re.compile(
        r'results_(width_[mp]\d+|radius_[mp]\d+|thickness_[mp]\d+)_w\d+\.\d+_r\d+\.\d+_t\d+\.\d+\.hdf5'
    )
    files = sorted([fp for fp in results_dir.glob('results_*.hdf5') if pat.match(fp.name)])
    
    # Add the updated center case
    center_file = results_dir / 'results_center_updated_w0.314_r0.043_t0.136.hdf5'
    if center_file.exists():
        files.append(center_file)
    
    # Also check for center_p0
    center_p0_file = results_dir / 'results_center_p0_w0.314_r0.043_t0.136.hdf5'
    if center_p0_file.exists() and center_p0_file not in files:
        files.append(center_p0_file)
    
    data = {'width': [], 'radius': [], 'thickness': []}
    
    print(f"\n📊 Processing {len(files)} result files...")
    print("=" * 70)
    
    # Disable plotting for batch processing
    ResonanceConfig.do_plot = False  # type: ignore
    
    for i, fp in enumerate(files, 1):
        try:
            # Progress indicator
            print(f"[{i}/{len(files)}] Analyzing {fp.name}...", end=" ", flush=True)
            res = analyze_q_factor(data_path=str(fp), wavelength_um=0.62, save_results=False)
            
            if 'q_factors' in res and len(res['q_factors']) > 0:
                q_factors = res['q_factors']
                frequencies_hz = res['frequencies_hz']
                frequencies_thz = frequencies_hz * 1e-12
                wavelengths = [299792458 / (f * 1e12) * 1e9 for f in frequencies_thz]  # Convert to nm
                
                # Handle center cases (applies to all parameters)
                if 'center_updated' in fp.name or 'center_p0' in fp.name:
                    variation = 0
                    mode_count = 0
                    for q, wl in zip(q_factors, wavelengths):
                        if q > q_threshold:  # Filter for high-Q modes only
                            data['width'].append((variation, wl, q, fp.name))
                            data['radius'].append((variation, wl, q, fp.name))
                            data['thickness'].append((variation, wl, q, fp.name))
                            mode_count += 1
                    print(f"✓ Center point: found {mode_count} high-Q modes (Q > {q_threshold})")
                    continue
                
                # Determine parameter type and extract variation
                param_type = None
                if 'width' in fp.name:
                    param_type = 'width'
                elif 'radius' in fp.name:
                    param_type = 'radius'
                elif 'thickness' in fp.name:
                    param_type = 'thickness'
                else:
                    continue
                
                # Extract variation from filename (e.g., m30, p15, m10, p20)
                var_match = re.search(rf'{param_type}_([mp]\d+)', fp.name)
                if var_match:
                    var_str = var_match.group(1)
                    # Parse variation: 'm30' -> -30, 'p15' -> 15
                    if var_str[0] == 'm':
                        variation = -int(var_str[1:])
                    else:  # 'p'
                        variation = int(var_str[1:])
                    
                    mode_count = 0
                    for q, wl in zip(q_factors, wavelengths):
                        if q > q_threshold:  # Filter for high-Q modes only
                            data[param_type].append((variation, wl, q, fp.name))
                            mode_count += 1
                    
                    print(f"✓ {param_type} {variation:+d}%: found {mode_count} high-Q modes")
                else:
                    print("⚠️  No variation match found")
                            
        except Exception as e:
            print(f'❌ Error: {e}')
    
    # Print summary
    print("=" * 70)
    print(f"📈 Summary of detected modes:")
    for param in ['width', 'radius', 'thickness']:
        print(f"  {param.capitalize()}: {len(data[param])} total mode points")
    
    return data


def save_mode_summary_csv(data: dict[str, list[tuple[int, float, float, str]]], 
                          csv_path: Path) -> None:
    """Save mode summary to CSV file."""
    import csv
    
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    with csv_path.open("w", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(["parameter", "variation_percent", "wavelength_nm", "q_factor", "source_file"])
        for param in ("width", "radius", "thickness"):
            for variation, wavelength_nm, q, src in data[param]:
                writer.writerow([param, variation, f"{wavelength_nm:.3f}", f"{q:.1f}", src])
    
    print(f"💾 Saved mode summary CSV: {csv_path}")


def load_saved_mode_data(csv_path: Path) -> dict[str, pd.DataFrame]:
    """Load saved mode data from CSV file."""
    if not csv_path.exists():
        raise FileNotFoundError(f"CSV file not found: {csv_path}")
    
    # Read the CSV data
    df = pd.read_csv(csv_path)
    
    # Filter for high-Q modes
    df_high_q = df[df['q_factor'] > q_threshold].copy()
    
    # Group by parameter
    data = {}
    for param in ['width', 'radius', 'thickness']:
        param_data = df_high_q[df_high_q['parameter'] == param].copy()
        if len(param_data) > 0:
            # Convert wavelength from nm to μm for consistency
            param_data = param_data.copy()
            param_data['wavelength_um'] = param_data['wavelength_nm'] / 1000
            data[param] = param_data
        else:
            data[param] = pd.DataFrame()
    
    return data


def create_wavelength_plot(data: dict[str, pd.DataFrame], output_path: Path, compact: bool = True) -> None:
    """Create wavelength sensitivity plot.
    
    Args:
        data: Dictionary with parameter data
        output_path: Path to save the plot
        compact: If True, use compact 36x30 mm size. If False, use normal size (6x5 inches)
    """
    
    if compact:
        # Compact size: 36x30 mm
        width_inches = 36 / 25.4
        height_inches = 30 / 25.4
        font_size = 7
        marker_size = 2.5
        line_width = 1.0
        spine_width = 0.5
        tick_width = 0.5
        tick_pad = 1
        legend_fontsize = 7
        legend_markerscale = 1.0
        legend_handlelength = 1.0
        tight_pad = 0.1
    else:
        # Normal size: 6x5 inches (larger, more readable)
        width_inches = 6.0
        height_inches = 5.0
        font_size = 10
        marker_size = 6
        line_width = 1.5
        spine_width = 1.0
        tick_width = 1.0
        tick_pad = 3
        legend_fontsize = 9
        legend_markerscale = 1.2
        legend_handlelength = 1.5
        tight_pad = 0.3
    
    # Set font sizes based on mode
    matplotlib.rcParams['font.size'] = font_size
    matplotlib.rcParams['axes.titlesize'] = font_size
    matplotlib.rcParams['axes.labelsize'] = font_size
    matplotlib.rcParams['xtick.labelsize'] = font_size
    matplotlib.rcParams['ytick.labelsize'] = font_size
    matplotlib.rcParams['legend.fontsize'] = legend_fontsize
    
    fig, ax = plt.subplots(1, 1, figsize=(width_inches, height_inches))
    
    params = ['width', 'radius', 'thickness']
    
    for param in params:
        if len(data[param]) > 0:
            param_data = data[param]
            
            # Group by variation and collect all modes for each
            variation_data = {}
            for _, row in param_data.iterrows():
                var = row['variation_percent']
                if var not in variation_data:
                    variation_data[var] = []
                variation_data[var].append((row['wavelength_um'], row['q_factor']))
            
            # For each variation, find the max Q mode
            max_q_data = {}
            for var in variation_data:
                modes = variation_data[var]
                # Find mode with highest Q-factor
                max_q_mode = max(modes, key=lambda x: x[1])
                max_q_data[var] = max_q_mode
            
            # Extract data for plotting
            variations_sorted = sorted(max_q_data.keys())
            wavelengths_um = [max_q_data[v][0] for v in variations_sorted]
            wavelengths_nm = [w * 1000 for w in wavelengths_um]  # Convert to nm
            
            # Plot wavelength vs parameter variation
            # Use italic LaTeX math notation for labels
            labels = {'width': r'$w$', 'radius': r'$r$', 'thickness': r'$t$'}
            ax.plot(variations_sorted, wavelengths_nm, 
                   color=COLORS[param], marker=MARKERS[param], 
                   linewidth=line_width, markersize=marker_size, 
                   label=labels[param], alpha=1.0)
    
    # Configure axes
    label_pad = 3 if compact else 5
    ax.set_xlabel('Variation (%)', labelpad=label_pad)
    ax.set_ylabel('Wavelength (nm)', labelpad=label_pad)
    
    # Make axis spines thinner
    for spine in ax.spines.values():
        spine.set_linewidth(spine_width)
    
    # Set five ticks on x-axis
    ax.set_xticks([-30, -15, 0, 15, 30])
    
    # Set three ticks on y-axis to specific values
    ax.set_yticks([590, 620, 650])
    
    # Configure ticks
    ax.tick_params(axis='both', which='major', pad=tick_pad, width=tick_width)
    
    # Create legend in bottom right corner without box
    if compact:
        legend = ax.legend(loc='lower right', bbox_to_anchor=(1.05, -0.05),
                  ncol=3, frameon=False, fancybox=False, shadow=False,
                  fontsize=legend_fontsize, columnspacing=0.5, handletextpad=0.3,
                  markerscale=legend_markerscale, handlelength=legend_handlelength)
        # Make legend symbols match plot size
        for handle in legend.legend_handles:
            handle.set_markersize(3)
    else:
        legend = ax.legend(loc='lower right', bbox_to_anchor=(1.0, 0.0),
                  ncol=3, frameon=False, fancybox=False, shadow=False,
                  fontsize=legend_fontsize, columnspacing=0.8, handletextpad=0.5,
                  markerscale=legend_markerscale, handlelength=legend_handlelength)
        # Make legend symbols match plot size
        for handle in legend.legend_handles:
            handle.set_markersize(6)
    
    # Add grid for normal size
    if not compact:
        ax.grid(True, alpha=0.3, linestyle='--', linewidth=0.5)
    
    # Make layout
    plt.tight_layout(pad=tight_pad)
    
    # Save as both PNG and SVG
    if compact:
        png_path = output_path.with_suffix('.png')
        svg_path = output_path.with_suffix('.svg')
        save_pad = 0.01
    else:
        png_path = output_path.parent / f"{output_path.name}_normal.png"
        svg_path = output_path.parent / f"{output_path.name}_normal.svg"
        save_pad = 0.1
    
    plt.savefig(png_path, dpi=300, bbox_inches='tight', pad_inches=save_pad)
    plt.savefig(svg_path, bbox_inches='tight', pad_inches=save_pad)
    
    print(f'💾 Wavelength plot saved as:')
    print(f'   PNG: {png_path}')
    print(f'   SVG: {svg_path}')
    print(f'   Size: {"Compact (36×30 mm)" if compact else "Normal (6×5 inches)"}')
    
    return fig, ax


